import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const romanizerPkg = require.resolve("lyric-romanizer/package.json");
const { pinyin } = createRequire(romanizerPkg)("pinyin-pro");

const RANGES = [
  { name: "EXT_A", start: 0x3400, end: 0x4dbf },
  { name: "UNIFIED", start: 0x4e00, end: 0x9fff },
  { name: "COMPAT", start: 0xf900, end: 0xfaff },
];

function initialForCodePoint(codePoint) {
  const grapheme = String.fromCodePoint(codePoint);
  const initial = pinyin(grapheme, { pattern: "first", toneType: "none" });
  if (!initial) return " ";
  const first = initial.codePointAt(0);
  if (first === undefined) return " ";
  const upper = String.fromCodePoint(first).toUpperCase();
  return /^[A-Z]$/.test(upper) ? upper : " ";
}

function buildRange(start, end) {
  let table = "";
  for (let codePoint = start; codePoint <= end; codePoint++) {
    table += initialForCodePoint(codePoint);
  }
  return table;
}

const tables = RANGES.map((range) => ({
  ...range,
  initials: buildRange(range.start, range.end),
}));

const rangeDecls = tables
  .map(
    (range) => `const ${range.name}_START = 0x${range.start.toString(16)};
const ${range.name}_INITIALS = ${JSON.stringify(range.initials)};`,
  )
  .join("\n\n");

const lookupArms = tables
  .map(
    (range) => `  if (
    codePoint >= ${range.name}_START &&
    codePoint < ${range.name}_START + ${range.name}_INITIALS.length
  ) {
    return letterOrNull(${range.name}_INITIALS.charAt(codePoint - ${range.name}_START));
  }`,
  )
  .join("\n");

const source = `// Generated by scripts/generate-han-pinyin-initials.mjs. Do not edit by hand.

${rangeDecls}

export function hanPinyinInitial(codePoint: number): string | null {
${lookupArms}
  return null;
}

function letterOrNull(letter: string): string | null {
  return letter === " " || letter.length === 0 ? null : letter;
}
`;

const outPath = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "src",
  "lib",
  "han-pinyin-initials.ts",
);
writeFileSync(outPath, source);

const mapped = tables.reduce(
  (count, range) =>
    count + [...range.initials].filter((letter) => letter !== " ").length,
  0,
);
console.log(
  `wrote ${outPath} (${mapped} initials across ${tables.reduce(
    (count, range) => count + range.initials.length,
    0,
  )} code points)`,
);
